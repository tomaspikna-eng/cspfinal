create or replace function public.set_score_event_identity()
returns trigger
language plpgsql
security definer
set search_path='public','pg_temp'
as $$
begin
  if new.player_identity_id is not null then return new; end if;

  if new.training_participant_id is not null then
    select player_identity_id into new.player_identity_id
    from public.training_session_participants
    where id=new.training_participant_id;
  elsif new.tournament_player_id is not null then
    select player_identity_id into new.player_identity_id
    from public.tournament_players
    where id=new.tournament_player_id;
  elsif new.player_profile_id is not null then
    select id into new.player_identity_id
    from public.player_identities
    where claimed_profile_id=new.player_profile_id and status<>'merged'
    limit 1;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_score_event_identity on public.score_events;
create trigger trg_score_event_identity
before insert or update of training_participant_id,tournament_player_id,player_profile_id,player_identity_id
on public.score_events
for each row execute function public.set_score_event_identity();

create or replace function public.sync_profile_player_identity()
returns trigger
language plpgsql
security definer
set search_path='public','pg_temp'
as $$
declare v_name text; v_norm text;
begin
  if new.role::text not in ('player','admin') then return new; end if;
  v_name := regexp_replace(btrim(coalesce(new.full_name,split_part(coalesce(new.email,''),'@',1),'Hráč')), '\s+', ' ', 'g');
  v_norm := public.normalize_player_identity_name(v_name);

  insert into public.player_identities(display_name,normalized_name,claimed_profile_id,status,created_source,created_by)
  values(v_name,v_norm,new.id,'claimed','account',new.id)
  on conflict (claimed_profile_id) do update
    set display_name=excluded.display_name,
        normalized_name=excluded.normalized_name,
        status='claimed',
        updated_at=now();
  return new;
end;
$$;

drop trigger if exists trg_profile_player_identity on public.profiles;
create trigger trg_profile_player_identity
after insert or update of full_name,email,role
on public.profiles
for each row execute function public.sync_profile_player_identity();

insert into public.player_identities(display_name,normalized_name,claimed_profile_id,status,created_source,created_by)
select regexp_replace(btrim(coalesce(p.full_name,split_part(coalesce(p.email,''),'@',1),'Hráč')), '\s+', ' ', 'g'),
       public.normalize_player_identity_name(coalesce(p.full_name,split_part(coalesce(p.email,''),'@',1),'Hráč')),
       p.id,'claimed','account_backfill',p.id
from public.profiles p
where p.role::text in ('player','admin')
on conflict (claimed_profile_id) do nothing;

update public.training_session_participants tsp
set player_identity_id=pi.id
from public.player_identities pi
where tsp.player_identity_id is null
  and tsp.player_id is not null
  and pi.claimed_profile_id=tsp.player_id;

update public.tournament_players tp
set player_identity_id=pi.id
from public.player_identities pi
where tp.player_identity_id is null
  and tp.user_id is not null
  and pi.claimed_profile_id=tp.user_id;

-- Name-only historical rows: reuse only when the name maps to exactly one active identity.
with unique_names as (
  select normalized_name,min(id::text)::uuid as identity_id
  from public.player_identities
  where status<>'merged'
  group by normalized_name
  having count(*)=1
)
update public.training_session_participants tsp
set player_identity_id=u.identity_id
from unique_names u
where tsp.player_identity_id is null
  and public.normalize_player_identity_name(tsp.display_name)=u.normalized_name;

