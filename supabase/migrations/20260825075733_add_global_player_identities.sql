create or replace function public.set_training_participant_identity()
returns trigger
language plpgsql
security definer
set search_path='public','pg_temp'
as $$
declare v public.player_identities;
begin
  if new.player_identity_id is not null then return new; end if;
  v := public.resolve_or_create_player_identity(new.display_name,new.player_id,'training_scoreboard');
  new.player_identity_id := v.id;
  return new;
end;
$$;

