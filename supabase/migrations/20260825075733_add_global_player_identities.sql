create table if not exists public.player_identities (
  id uuid primary key default gen_random_uuid(),
  csp_number bigint generated by default as identity unique not null,
  display_name text not null check (length(btrim(display_name)) between 1 and 160),
  normalized_name text not null,
  claimed_profile_id uuid unique references public.profiles(id) on delete set null,
  status text not null default 'unclaimed' check (status in ('unclaimed','claimed','merged')),
  created_source text not null default 'manual',
  created_by uuid references public.profiles(id) on delete set null,
  merged_into_id uuid references public.player_identities(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists player_identities_normalized_name_idx on public.player_identities(normalized_name) where status <> 'merged';
create index if not exists player_identities_claimed_profile_idx on public.player_identities(claimed_profile_id) where claimed_profile_id is not null;

alter table public.player_identities enable row level security;

drop policy if exists player_identities_authenticated_read on public.player_identities;
create policy player_identities_authenticated_read on public.player_identities
for select to authenticated
using (status <> 'merged');

create or replace function public.normalize_player_identity_name(p_name text)
returns text
language sql
immutable
set search_path=''
as $$
  select lower(regexp_replace(btrim(coalesce(p_name,'')), '\s+', ' ', 'g'));
$$;

create or replace function public.format_csp_player_id(p_number bigint)
returns text
language sql
immutable
set search_path=''
as $$
  select lpad(coalesce(p_number,0)::text, 6, '0');
$$;

create or replace function public.resolve_or_create_player_identity(
  p_display_name text,
  p_profile_id uuid default null,
  p_source text default 'manual'
)
returns public.player_identities
language plpgsql
security definer
set search_path='public','pg_temp'
as $$
declare
  v_name text;
  v_norm text;
  v_identity public.player_identities;
  v_count int;
begin
  if auth.uid() is null then
    raise exception 'AUTHENTICATION_REQUIRED';
  end if;

  v_name := regexp_replace(btrim(coalesce(p_display_name,'')), '\s+', ' ', 'g');
  if length(v_name) < 1 then raise exception 'PLAYER_NAME_REQUIRED'; end if;
  if length(v_name) > 160 then raise exception 'PLAYER_NAME_TOO_LONG'; end if;
  v_norm := public.normalize_player_identity_name(v_name);

  if p_profile_id is not null then
    select * into v_identity
    from public.player_identities
    where claimed_profile_id=p_profile_id and status<>'merged'
    limit 1;

    if v_identity.id is not null then
      update public.player_identities
      set display_name=case when nullif(v_name,'') is not null then v_name else display_name end,
          normalized_name=case when nullif(v_norm,'') is not null then v_norm else normalized_name end,
          status='claimed',
          updated_at=now()
      where id=v_identity.id
      returning * into v_identity;
      return v_identity;
    end if;

    insert into public.player_identities(display_name,normalized_name,claimed_profile_id,status,created_source,created_by)
    values(v_name,v_norm,p_profile_id,'claimed',coalesce(nullif(btrim(p_source),''),'manual'),auth.uid())
    returning * into v_identity;
    return v_identity;
  end if;

  select count(*) into v_count
  from public.player_identities
  where normalized_name=v_norm and status<>'merged';

  if v_count=1 then
    select * into v_identity
    from public.player_identities
    where normalized_name=v_norm and status<>'merged'
    limit 1;
    return v_identity;
  end if;

  insert into public.player_identities(display_name,normalized_name,status,created_source,created_by)
  values(v_name,v_norm,'unclaimed',coalesce(nullif(btrim(p_source),''),'manual'),auth.uid())
  returning * into v_identity;
  return v_identity;
end;
$$;

grant execute on function public.resolve_or_create_player_identity(text,uuid,text) to authenticated;
grant execute on function public.format_csp_player_id(bigint) to anon,authenticated;

